def find(name):
    if os.path.exists(os.path.join(ROOT, name)): return os.path.join(ROOT, name)   # a path from the repo root
    for d in sorted(os.listdir(SRC)):
        p = os.path.join(SRC, d, 'media', name)
        if os.path.exists(p): return p
    raise FileNotFoundError(name)
out = {}
with tempfile.TemporaryDirectory() as tmp:
    for key, name in COVERS.items():
        name, anchor = name if isinstance(name, tuple) else (name, 'centre')
        jpg = os.path.join(tmp, key + '.jpg')
        if anchor == 'fit':
            sw, sh = map(int, subprocess.run(['ffprobe', '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', find(name)], capture_output=True, text=True, check=True).stdout.strip().split(','))
            ih = round(W * sh / sw / 2) * 2; band = (H - ih) // 2
        vf = (f'scale={W}:{ih}:flags=lanczos,pad={W}:{H}:0:{band},fillborders=top={band}:bottom={H - ih - band}:mode=smear' if anchor == 'fit' else
              f'scale={W}:{H}:force_original_aspect_ratio=increase:flags=lanczos,crop={W}:{H}' + {'left': ':0:(ih-oh)/2', 'top': ':(iw-ow)/2:0'}.get(anchor, ''))
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', find(name), '-vf', vf,
                        '-frames:v', '1', '-q:v', '3', jpg], check=True)   # one frame: the first, for a video
        out[key] = 'data:image/jpeg;base64,' + base64.b64encode(open(jpg, 'rb').read()).decode()
        open(os.path.join(ROOT, 'assets/data', 'card-' + key + '.jpg'), 'wb').write(open(jpg, 'rb').read())   # preview copy
js = '// generated by tools/card_images.py, do not edit\nwindow.CARD_IMG={\n' + ',\n'.join(f'{k}:"{v}"' for k, v in out.items()) + '};\n'
open(os.path.join(ROOT, 'assets/data/card-images.js'), 'w').write(js)
print(len(out), 'covers,', round(len(js) / 1e6, 2), 'MB')
# projects without a video show their cover as the page's main image: there it keeps its own ratio, uncropped (assets/data/cover/<slug>.jpg,
# 2000 px on the long edge, flattened on white). Keep COVER_AR in index.html in step with the ratios printed here
from PIL import Image
os.makedirs(os.path.join(ROOT, 'assets/data/cover'), exist_ok=True)
for key, name in COVERS.items():
    if key in FIRST_FRAME: continue
    name = name[0] if isinstance(name, tuple) else name
    im = Image.open(find(name)).convert('RGBA')
    bg = Image.new('RGB', im.size, 'white'); bg.paste(im, mask=im.getchannel('A')); im = bg
    k = 2000 / max(im.size)
    if k < 1: im = im.resize((round(im.width * k), round(im.height * k)), Image.LANCZOS)
    im.save(os.path.join(ROOT, 'assets/data/cover', key + '.jpg'), quality=85, optimize=True, progressive=True)
    print(f'page cover {key}: {im.width}x{im.height}, ratio {im.width / im.height:.2f}')
